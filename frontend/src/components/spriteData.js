// ─── Emotion face overlays ───────────────────
// Each overlay is {rows: {rowIndex: string}} — replaces specific rows in the base sprite.
// Only the face area is changed; body remains the same.

function makeOverlays(eyeRows, mouthRows) {
  // eyeRows: [[rowIdx, string], ...], mouthRows: [[rowIdx, string], ...]
  const rows = {}
  for (const [idx, str] of eyeRows) rows[idx] = str
  for (const [idx, str] of mouthRows) rows[idx] = str
  return { rows }
}

