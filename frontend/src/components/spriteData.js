// ─── Sprite builder ──────────────────────────

const MASCOT_ALIASES = {
  wolf: 'fox',
  tiger: 'cat',
  frog: 'robot',
  octopus: 'crystal',
  alien: 'ghost',
  bat: 'dragon',
  bee: 'owl',
  eagle: 'owl',
  unicorn: 'llama',
  raccoon: 'panda',
}

function resolveMascot(mascot) {
  const resolved = MASCOT_ALIASES[mascot] || mascot
  return BODIES[resolved] ? resolved : 'wizard'
}

/**
 * Build the final 16x16 pixel grid for a mascot+emotion.
 * Returns array of 16 strings (rows).
 */
export function buildSprite(mascot, emotion) {
  const spriteMascot = resolveMascot(mascot)
  const base = BODIES[spriteMascot] || BODIES.wizard
  const overlays = EMOTION_OVERLAYS[spriteMascot] || EMOTION_OVERLAYS.wizard
  const overlay = overlays[emotion] || null

  if (!overlay) return [...base]

  const result = [...base]
  for (const [rowIdx, rowStr] of Object.entries(overlay.rows)) {
    const idx = Number(rowIdx)
    if (idx >= 0 && idx < 16) {
      // Merge: only replace non-dot characters from overlay
      const baseRow = result[idx] || ''
      let merged = ''
      for (let c = 0; c < 16; c++) {
        const oc = rowStr[c]
        const bc = baseRow[c] || '.'
        merged += (oc && oc !== '.' && c < rowStr.length) ? oc : bc
      }
      result[idx] = merged
    }
  }
  return result
}

/**
 * Get the color palette for a mascot type.
 */
export function getPalette(mascot) {
  return PALETTES[resolveMascot(mascot)] || PALETTES.wizard
}

